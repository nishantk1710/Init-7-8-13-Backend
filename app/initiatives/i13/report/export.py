"""A saved summary report as an Excel workbook.

The page is what people read; the workbook is for the reader who wants to
filter or forward the rows behind it. It is written from the saved report
only -- never re-read from the snapshot -- so the workbook and the page it was
downloaded from always agree.

Same openpyxl conventions as the I07 export (bold header row, frozen panes),
and the screens' words for every status (``labels.py``).
"""

from __future__ import annotations

from io import BytesIO
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font
from openpyxl.worksheet.worksheet import Worksheet

from app.initiatives.i13.report.labels import EXCEPTION_STATUS, EXCEPTION_TYPE, PLAN_STATUS, STOCK_TYPE

_BOLD = Font(bold=True)
_TITLE = Font(bold=True, size=14)
_WRAP = Alignment(wrap_text=True, vertical="top")


def _label(table: dict[str, str], code: str) -> str:
    return table.get(code, code.replace("_", " ").capitalize())


def _table(sheet: Worksheet, headers: list[str], rows: list[list[Any]]) -> None:
    sheet.append(headers)
    for cell in sheet[sheet.max_row]:
        cell.font = _BOLD
    # A string, not sheet.cell(...): fetching a cell creates it, and an empty
    # row would land between the header and the data.
    sheet.freeze_panes = f"A{sheet.max_row + 1}"
    for row in rows:
        sheet.append(["" if v is None else v for v in row])
    for index, header in enumerate(headers, start=1):
        sheet.column_dimensions[sheet.cell(row=1, column=index).column_letter].width = max(14, len(header) + 4)


def _summary_sheet(sheet: Worksheet, meta: dict[str, Any], facts: dict[str, Any], narrative: dict[str, Any]) -> None:
    sheet.title = "Summary"
    sheet.column_dimensions["A"].width = 22
    sheet.column_dimensions["B"].width = 110

    sheet.append(["OAR Utilization summary report"])
    sheet["A1"].font = _TITLE
    sheet.append([])
    for label, value in [
        ("Scope", facts["scope"]["label"]),
        ("Data as of", facts.get("data_as_of")),
        ("Generated", meta.get("generated_at")),
        ("Generated by", meta.get("generated_by")),
        ("Wording", "AI-written" if narrative.get("source") == "MODEL" else "Standard template"),
    ]:
        sheet.append([label, value])
        sheet.cell(row=sheet.max_row, column=1).font = _BOLD
    if facts.get("valuation_is_mocked"):
        sheet.append(["Note", "Stock valuation is not yet live; no money values are reported."])
    sheet.append([])

    def block(title: str, lines: list[str]) -> None:
        sheet.append([title])
        sheet.cell(row=sheet.max_row, column=1).font = _BOLD
        for line in lines:
            sheet.append(["", line])
            sheet.cell(row=sheet.max_row, column=2).alignment = _WRAP
        sheet.append([])

    block("Headline", [narrative["headline"]])
    block("Key findings", narrative.get("findings", []))
    block("Risks", narrative.get("risks", []))
    block("Actions", [f"{a['action']} (Owner: {a['owner']})" for a in narrative.get("actions", [])])


def build_report_workbook(meta: dict[str, Any], report: dict[str, Any]) -> BytesIO:
    """``meta``: id, generated_at, generated_by. ``report``: the saved payload."""
    facts, narrative = report["facts"], report["narrative"]
    book = Workbook()
    _summary_sheet(book.active, meta, facts, narrative)

    pos, plans, grni, exc = facts["positions"], facts["plans"], facts["gr_not_issued"], facts["exceptions"]
    rows: list[list[Any]] = [["OAR materials", "Total", pos["total"], None]]
    for band, pct_key in (("FAST", "fast_pct"), ("SLOW", "slow_pct"), ("NON_MOVING", "non_moving_pct")):
        rows.append(["Stock type", _label(STOCK_TYPE, band), pos[band], pos[pct_key]])
    for status, count in plans["acquired_vs_plan"].items():
        rows.append(["Acquired vs plan", _label(PLAN_STATUS, status), count, None])
    rows.append(["Plans", "Planned Overdue", plans["plan_breach_count"], None])
    rows.append(["Plans", "Non-AI", plans["no_plan_count"], None])
    rows.append(["Received not issued", f"OAR materials ({grni['threshold_days']}+ days)", grni["position_count"], None])
    rows.append(["Received not issued", "Reservation lines", grni["open_line_count"], None])
    for status, count in exc["by_status"].items():
        rows.append(["Procurement exceptions by status", _label(EXCEPTION_STATUS, status), count, None])
    for kind, count in exc["by_type"].items():
        rows.append(["Procurement exceptions by type", _label(EXCEPTION_TYPE, kind), count, None])
    _table(book.create_sheet("Key figures"), ["Area", "Measure", "Value", "% of OAR materials"], rows)

    _table(
        book.create_sheet("Received not issued"),
        ["Material", "Description", "Plant", "Reservation", "PO number", "Outstanding qty", "Days since GR"],
        [
            [g["material"], g["description"], g["plant"], g["reservation"], g["po_number"],
             g["outstanding_quantity"], g["days_since_gr"]]
            for g in grni["longest_waiting"]
        ],
    )
    _table(
        book.create_sheet("Oldest exceptions"),
        ["Exception", "Type", "Status", "Material", "Description", "Plant", "Reservation", "Days open"],
        [
            [e["exception_id"], _label(EXCEPTION_TYPE, e["type"]), _label(EXCEPTION_STATUS, e["status"]),
             e["material"], e["description"], e["plant"], e["reservation"], e["days_open"]]
            for e in exc["oldest_unresolved"]
        ],
    )

    buffer = BytesIO()
    book.save(buffer)
    buffer.seek(0)
    return buffer
