"""The automatic Quarterly Report: decide whether one is due, and generate it once.

Nothing in this application generated the report on its own before this module (see
``docs/i07_quarterly_report_scheduling.md``: the Logic App / WebJob it relies on is an Azure resource, not code). This
is the in-app alternative, and it adds no timer of its own: it is one more step in the nightly I07 watcher
(``app.initiatives.i7.pipeline_scheduler``), after the pipeline check and the KPI snapshots, **off unless
``I7_QUARTERLY_REPORT_AUTO_ENABLED`` is set** and only ever reached when the watcher itself is on.

It calls the same ``generate_quarterly_report`` and ``save_report`` as the API route and the CLI -- a third caller of
one service, not a parallel implementation.

When is a report due?
---------------------
Everything below holds for a month's report just as for a quarter's (``kind="month"``): the period in question is the
latest one to have closed, and the same rules, lock and failure handling apply. In the nightly watcher the monthly step
is switched on by its own flag, ``I7_MONTHLY_REPORT_AUTO_ENABLED``.

The quarter in question is always :func:`latest_closed_period` as of the injected ``now``, so a quarter that is still
running is never generated automatically. It is due when

* it closed no more than ``window_days`` ago -- so switching this on mid-quarter does not quietly produce a report for
  a quarter that closed weeks ago (generate that one by hand), and
* there is no COMPLETED report for it that was **generated after the quarter closed**. A report someone generated by
  hand while the quarter was still running is a partial one, and is replaced; one generated on or after the day after
  quarter-end is final, and is left alone.

Why it is safe to run on every tick and on every instance
---------------------------------------------------------
* **Idempotent.** ``save_report`` upserts by quarter, and a final report makes the step a no-op, so a retry, a restart
  or two instances cannot create a duplicate or regenerate a finished report.
* **Locked.** Generation takes ~40-50 s. A SQL Server application lock admits one instance; the other reports BUSY. The
  decision is re-read once the lock is held, so an instance that lost the race finds the finished report and stands down.
* **Waits for the pipeline.** While a pipeline run is in progress the recommendations are being rewritten; a report
  read mid-run would describe a half-built state, so the step waits for a later tick (same rule as the snapshots).
* **Failures are logged, never raised.** A failed attempt writes nothing -- in particular it never overwrites an
  existing report with a FAILED row -- and the next open slot tries again (the scheduler records the failure so one
  slot is not retried every tick).
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from datetime import date, datetime, timezone
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.core.logging import get_logger
from app.initiatives.i7.locking import application_lock
from app.initiatives.i7.reporting.period import MONTH, QUARTER, latest_closed_period, resolve_period
from app.initiatives.i7.reporting.repository import get_report, save_report
from app.initiatives.i7.reporting.service import generate_quarterly_report
from app.models.i7_pipeline import STATUS_RUNNING, PipelineRun

logger = get_logger(__name__)

LOCK_NAME = "i7_quarterly_report_auto"

#: One lock per kind of report, so a month's and a quarter's generation never wait on each other.
LOCK_NAMES = {QUARTER: LOCK_NAME, MONTH: "i7_monthly_report_auto"}

#: Days after a quarter closes during which the automatic step will still generate it.
DEFAULT_WINDOW_DAYS = 7

# Decision states
DUE = "DUE"
UP_TO_DATE = "UP_TO_DATE"
OUTSIDE_WINDOW = "OUTSIDE_WINDOW"

# Result actions
GENERATED = "GENERATED"
WAITING = "WAITING"
BUSY = "BUSY"
FAILED = "FAILED"


@dataclass(frozen=True)
class Decision:
    quarter: str
    state: str
    reason: str

    @property
    def due(self) -> bool:
        return self.state == DUE


@dataclass(frozen=True)
class AutoResult:
    quarter: str
    action: str
    detail: str = ""
    report_id: int | None = None

    def __str__(self) -> str:
        return f"{self.quarter}: {self.action}" + (f" ({self.detail})" if self.detail else "")


def _utc_date(now: datetime) -> date:
    if now.tzinfo is None:
        raise ValueError("the quarterly report step needs a timezone-aware time")
    return now.astimezone(timezone.utc).date()


def assess(session: Session, now: datetime, window_days: int = DEFAULT_WINDOW_DAYS, kind: str = QUARTER) -> Decision:
    """Is a report due as of ``now``? Reads one row; writes nothing.

    ``kind`` is the sort of period: ``"quarter"`` (the default) or ``"month"``. The rules are the same for both -- the
    period in question is the latest one that has closed, and the words below say "quarter" or "month" accordingly.
    """
    today = _utc_date(now)
    quarter = latest_closed_period(kind, today)  # the period's label; the name is the report's own ("quarter")
    _, period_end = resolve_period(quarter)

    age = (today - period_end).days
    if age > window_days:
        return Decision(
            quarter, OUTSIDE_WINDOW,
            f"closed {age} days ago; the automatic step covers only the first {window_days} days after a {kind} closes",
        )

    row = get_report(session, quarter)
    if row is None:
        return Decision(quarter, DUE, f"no report exists for this {kind}")
    if row.status != "COMPLETED" or row.report_json is None:
        return Decision(quarter, DUE, f"the saved report is {row.status}")
    generated_on = row.generated_at.astimezone(timezone.utc).date() if row.generated_at.tzinfo else row.generated_at.date()
    if generated_on <= period_end:
        return Decision(quarter, DUE, f"the saved report was generated on {generated_on}, before the {kind} closed")
    return Decision(quarter, UP_TO_DATE, f"final report already generated on {generated_on}")


def _pipeline_running(session: Session) -> bool:
    return bool(
        session.execute(
            select(func.count()).select_from(PipelineRun).where(PipelineRun.status == STATUS_RUNNING)
        ).scalar_one()
    )


def generate_due_quarterly_report(
    session_factory: Callable[[], Session],
    now: datetime | None = None,
    *,
    window_days: int = DEFAULT_WINDOW_DAYS,
    lock: Any = None,
    generate: Callable[..., Any] = generate_quarterly_report,
    save: Callable[..., Any] = save_report,
    kind: str = QUARTER,
) -> AutoResult:
    """Generate and save the latest closed period's report (``kind``: a quarter, or a month) if one is due, else say
    why not. Never raises.

    ``now`` is the clock (a test passes a fixed one); ``generate``/``save`` default to the real service and repository
    and are parameters only so a test can make either fail. ``lock`` defaults to the real cross-instance lock, one per
    kind so a month's report and a quarter's (both due on the first of January, April, ...) can run side by side.
    """
    now = now or datetime.now(timezone.utc)
    quarter = latest_closed_period(kind, _utc_date(now))
    try:
        with session_factory() as session:
            decision = assess(session, now, window_days, kind)
            if not decision.due:
                return AutoResult(decision.quarter, decision.state, decision.reason)
            if _pipeline_running(session):
                return AutoResult(decision.quarter, WAITING, "a pipeline run is in progress")

            lock = lock if lock is not None else application_lock(LOCK_NAMES[kind])
            if not lock.acquire():
                return AutoResult(decision.quarter, BUSY, "another instance is generating it")
            try:
                session.rollback()  # end the read transaction so the re-check below sees what the other instance saved
                decision = assess(session, now, window_days, kind)
                if not decision.due:
                    return AutoResult(decision.quarter, decision.state, decision.reason)

                logger.info(
                    "i7.reporting.auto.generate.start", extra={"quarter": decision.quarter, "reason": decision.reason}
                )
                report = generate(session, decision.quarter, today=_utc_date(now), generated_at=now)
                row = save(session, decision.quarter, report, status="COMPLETED")
                session.commit()
                logger.info(
                    "i7.reporting.auto.generate.done", extra={"quarter": decision.quarter, "report_id": row.id}
                )
                return AutoResult(decision.quarter, GENERATED, decision.reason, report_id=row.id)
            finally:
                lock.release()
    except Exception as exc:  # noqa: BLE001 -- a failed attempt must never end the nightly loop
        logger.exception("i7.reporting.auto.generate.failed", extra={"quarter": quarter})
        return AutoResult(quarter, FAILED, f"{type(exc).__name__}: {exc}")
