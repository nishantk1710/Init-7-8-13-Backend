"""The automatic quarterly report: when it is due, and that it generates exactly once.

Offline and isolated: an in-memory SQLite database per test, the **real** report generator and repository, an injected
clock and a fake lock. Nothing here can reach the shared database, change the system clock, or start a pipeline run.
"""

from __future__ import annotations

from datetime import date, datetime

import pytest
from sqlalchemy import select

from app.initiatives.i7.reporting import auto_generate
from app.initiatives.i7.reporting.auto_generate import (
    BUSY, DUE, FAILED, GENERATED, OUTSIDE_WINDOW, UP_TO_DATE, WAITING, assess, generate_due_quarterly_report,
)
from app.initiatives.i7.reporting.repository import save_report
from app.initiatives.i7.reporting.service import generate_quarterly_report
from app.models.i7_pipeline import STATUS_RUNNING, PipelineRun
from app.models.i7_reporting import QuarterlyReportRecord
from app.schemas.i7.reports import PeriodStatus, QuarterlyReport
from tests.i7.reporting.quarterly_fixtures import (
    UTC, NoLock, RefusedLock, at, make_factory, seed_q4_2026, stub_stockout,
)

JAN_1_NIGHT = datetime(2027, 1, 1, 20, 5, tzinfo=UTC)  # the first nightly slot after Q4 2026 closes
OCT_27 = datetime(2026, 10, 27, 20, 5, tzinfo=UTC)


@pytest.fixture(autouse=True)
def _stockout(monkeypatch):
    stub_stockout(monkeypatch)


@pytest.fixture
def factory():
    f = make_factory()
    with f() as session:
        seed_q4_2026(session)
    return f


def rows(factory) -> list[QuarterlyReportRecord]:
    with factory() as session:
        return list(session.execute(select(QuarterlyReportRecord)).scalars())


def save_partial(factory, *, on: date) -> None:
    """A report someone generated by hand on ``on`` -- while Q4 2026 was still running, so it is partial."""
    with factory() as session:
        report = generate_quarterly_report(
            session, "Q4 2026", today=on, generated_at=datetime(on.year, on.month, on.day, 9, tzinfo=UTC)
        )
        save_report(session, "Q4 2026", report, status="COMPLETED")
        session.commit()


class Calls:
    """Counts calls to the real generator, so a test can prove it was (not) run."""

    def __init__(self) -> None:
        self.count = 0

    def __call__(self, *args, **kwargs):
        self.count += 1
        return generate_quarterly_report(*args, **kwargs)


# --- is a report due? --------------------------------------------------------------------------


@pytest.mark.parametrize(
    "now,quarter,state",
    [
        (OCT_27, "Q3 2026", OUTSIDE_WINDOW),  # today: Q3 closed 27 days ago -- switching the step on now generates nothing
        (datetime(2026, 12, 31, 20, 5, tzinfo=UTC), "Q3 2026", OUTSIDE_WINDOW),  # Q4 has not closed yet
        (JAN_1_NIGHT, "Q4 2026", DUE),
        (datetime(2027, 1, 7, 20, 5, tzinfo=UTC), "Q4 2026", DUE),  # last day of the 7-day window
        (datetime(2027, 1, 8, 20, 5, tzinfo=UTC), "Q4 2026", OUTSIDE_WINDOW),  # one day past it
    ],
)
def test_which_quarter_is_targeted_and_whether_it_is_in_the_window(factory, now, quarter, state):
    with factory() as session:
        decision = assess(session, now)
    assert (decision.quarter, decision.state) == (quarter, state)


def test_a_naive_time_is_refused_rather_than_guessed_at(factory):
    with pytest.raises(ValueError, match="timezone-aware"):
        generate_due_quarterly_report(factory, datetime(2027, 1, 1, 20, 5), lock=NoLock())


def test_the_window_is_a_parameter(factory):
    with factory() as session:
        assert assess(session, datetime(2027, 1, 20, 20, 5, tzinfo=UTC), window_days=31).state == DUE


def test_a_report_still_missing_is_due_and_a_failed_one_is_due_again(factory):
    with factory() as session:
        assert assess(session, JAN_1_NIGHT).due
        session.add(QuarterlyReportRecord(
            quarter="Q4 2026", period_start=date(2026, 10, 1), period_end=date(2026, 12, 31), generated_at=at(2027, 1, 1),
            status="FAILED", report_version="1.2", report_json=None, error="boom",
        ))
        session.commit()
        decision = assess(session, JAN_1_NIGHT)
    assert decision.due and "FAILED" in decision.reason


# --- generating it, once -----------------------------------------------------------------------


def test_the_first_night_after_quarter_end_generates_and_saves_the_completed_report(factory):
    lock = NoLock()
    result = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=lock)

    assert (result.quarter, result.action) == ("Q4 2026", GENERATED)
    [row] = rows(factory)
    assert (row.quarter, row.status, row.id) == ("Q4 2026", "COMPLETED", result.report_id)

    report = QuarterlyReport.from_report_json(row.report_json)
    assert report.metadata.quarter == "Q4 2026"
    assert report.management.period.status is PeriodStatus.COMPLETE  # written as a finished quarter, not a running one
    assert report.metadata.generated_at == JAN_1_NIGHT  # the injected clock, not the real one
    assert report.recommendations.total == 7  # the synthetic Oct + Nov + Dec rows
    assert lock.acquired == lock.released == 1


def test_running_it_again_changes_nothing_and_does_not_regenerate(factory):
    calls = Calls()
    first = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=NoLock(), generate=calls)
    before = rows(factory)[0]
    snapshot = (before.id, before.generated_at, before.report_json)

    for later in (datetime(2027, 1, 1, 22, 5, tzinfo=UTC), datetime(2027, 1, 2, 20, 5, tzinfo=UTC)):
        again = generate_due_quarterly_report(factory, later, lock=NoLock(), generate=calls)
        assert (again.action, again.report_id) == (UP_TO_DATE, None)

    [after] = rows(factory)
    assert (after.id, after.generated_at, after.report_json) == snapshot  # one row, byte-for-byte unchanged
    assert calls.count == 1  # the generator ran once
    assert first.action == GENERATED


def test_a_partial_report_made_by_hand_during_the_quarter_is_replaced_at_quarter_end(factory):
    save_partial(factory, on=date(2026, 12, 1))
    [partial] = rows(factory)
    assert QuarterlyReport.from_report_json(partial.report_json).management.period.status is PeriodStatus.IN_PROGRESS

    result = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=NoLock())

    assert result.action == GENERATED
    [final] = rows(factory)
    assert final.id == partial.id  # the same row, upserted -- never a second one
    assert QuarterlyReport.from_report_json(final.report_json).management.period.status is PeriodStatus.COMPLETE


def test_a_final_report_generated_after_quarter_end_by_any_route_is_left_alone(factory):
    with factory() as session:
        report = generate_quarterly_report(session, "Q4 2026", today=date(2027, 1, 2), generated_at=at(2027, 1, 2))
        save_report(session, "Q4 2026", report, status="COMPLETED")
        session.commit()
    calls = Calls()
    result = generate_due_quarterly_report(factory, datetime(2027, 1, 3, 20, 5, tzinfo=UTC), lock=NoLock(), generate=calls)
    assert result.action == UP_TO_DATE and calls.count == 0


def test_nothing_is_generated_outside_the_window_even_though_no_report_exists(factory):
    calls = Calls()
    result = generate_due_quarterly_report(factory, OCT_27, lock=NoLock(), generate=calls)
    assert (result.quarter, result.action) == ("Q3 2026", OUTSIDE_WINDOW)
    assert calls.count == 0 and rows(factory) == []


# --- failure handling --------------------------------------------------------------------------


def test_a_failed_generation_is_reported_not_raised_and_writes_nothing(factory):
    lock = NoLock()

    def boom(*args, **kwargs):
        raise RuntimeError("database blip")

    result = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=lock, generate=boom)
    assert result.action == FAILED and "RuntimeError: database blip" in result.detail
    assert rows(factory) == []
    assert lock.released == 1  # released even though generation raised


def test_a_failed_attempt_never_overwrites_a_report_that_already_exists(factory):
    save_partial(factory, on=date(2026, 12, 1))
    before = rows(factory)[0].report_json

    def boom(*args, **kwargs):
        raise RuntimeError("database blip")

    assert generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=NoLock(), generate=boom).action == FAILED
    assert rows(factory)[0].report_json == before and rows(factory)[0].status == "COMPLETED"


def test_a_failure_while_saving_is_rolled_back_and_leaves_no_partial_row(factory):
    def failing_save(session, quarter, report, **kwargs):
        save_report(session, quarter, report, **kwargs)  # the row is added and flushed...
        raise RuntimeError("commit failed")  # ...and then the save fails before the commit

    result = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=NoLock(), save=failing_save)
    assert result.action == FAILED
    assert rows(factory) == []
    # and the next attempt succeeds: nothing was left half-done
    assert generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=NoLock()).action == GENERATED


# --- locking and the pipeline ------------------------------------------------------------------


def test_another_instance_holding_the_lock_means_this_one_does_nothing(factory):
    calls, lock = Calls(), RefusedLock()
    result = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=lock, generate=calls)
    assert result.action == BUSY and calls.count == 0 and rows(factory) == []


def test_an_instance_that_lost_the_race_finds_the_finished_report_and_stands_down(factory):
    """Both instances saw the report as due; the other finished while this one waited for the lock."""
    calls = Calls()

    class LockThatWaitsForTheOtherInstance(NoLock):
        def acquire(self) -> bool:
            with factory() as other:
                report = generate_quarterly_report(other, "Q4 2026", today=date(2027, 1, 1), generated_at=JAN_1_NIGHT)
                save_report(other, "Q4 2026", report, status="COMPLETED")
                other.commit()
            return super().acquire()

    result = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=LockThatWaitsForTheOtherInstance(), generate=calls)
    assert result.action == UP_TO_DATE and calls.count == 0
    assert len(rows(factory)) == 1


def test_it_waits_while_a_pipeline_run_is_in_progress(factory):
    with factory() as session:
        session.add(PipelineRun(status=STATUS_RUNNING, trigger_reason="nightly", started_at=JAN_1_NIGHT, source_fingerprint="f"))
        session.commit()
    calls, lock = Calls(), NoLock()
    result = generate_due_quarterly_report(factory, JAN_1_NIGHT, lock=lock, generate=calls)
    assert result.action == WAITING
    assert calls.count == 0 and lock.acquired == 0 and rows(factory) == []  # it did not even take the lock


def test_the_step_shares_the_one_service_with_the_api_and_the_cli():
    """A third caller of one service, never a parallel implementation."""
    from app.api.i7 import reports as api
    from app.reporting import generate_quarterly as cli

    assert auto_generate.generate_quarterly_report is api.generate_quarterly_report is cli.generate_quarterly_report
    assert auto_generate.save_report is api.save_report is cli.save_report
